func TestUpdateNpmLockBumpsTheLockedPackageOnly(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name    string
		content string
		want    string
	}{
		{
			name: "bumps the top level and the root package of a lockfile version 3",
			content: `{
  "name": "@kirchdev/duxt",
  "version": "0.8.1",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "@kirchdev/duxt",
      "version": "0.8.1",
      "license": "MIT",
      "dependencies": {
        "defu": "^6.1.4"
      }
    },
    "node_modules/defu": {
      "version": "6.1.4",
      "resolved": "https://registry.npmjs.org/defu/-/defu-6.1.4.tgz"
    }
  }
}
`,
			want: `{
  "name": "@kirchdev/duxt",
  "version": "0.9.0",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "@kirchdev/duxt",
      "version": "0.9.0",
      "license": "MIT",
      "dependencies": {
        "defu": "^6.1.4"
      }
    },
    "node_modules/defu": {
      "version": "6.1.4",
      "resolved": "https://registry.npmjs.org/defu/-/defu-6.1.4.tgz"
    }
  }
}
`,
		},
		{
			name: "bumps the top level of a lockfile version 1, which has no packages",
			content: `{
  "name": "legacy-app",
  "version": "2.3.0",
  "lockfileVersion": 1,
  "dependencies": {
    "lodash": {
      "version": "4.17.21"
    }
  }
}
`,
			want: `{
  "name": "legacy-app",
  "version": "0.9.0",
  "lockfileVersion": 1,
  "dependencies": {
    "lodash": {
      "version": "4.17.21"
    }
  }
}
`,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := updater.UpdateNpmLock(tc.content, "0.9.0")
			if err != nil {
				t.Fatalf("UpdateNpmLock() error = %v", err)
			}
			if got != tc.want {
				t.Fatalf("UpdateNpmLock() =\n%s\nwant\n%s", got, tc.want)
			}
		})
	}
}

func TestUpdateNpmLockRejectsALockfileWithNoTopLevelVersion(t *testing.T) {
	t.Parallel()
	content := `{
  "name": "private-app",
  "lockfileVersion": 3,
  "packages": {
    "node_modules/defu": {
      "version": "6.1.4"
    }
  }
}
`
	if _, err := updater.UpdateNpmLock(content, "1.0.0"); err == nil {
		t.Fatal("UpdateNpmLock() error = nil, want an error")
	}
}

