func TestUpdateGemfileLockBumpsTheSpecsEntryOfTheGemNamedByKey(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name    string
		version string
		entry   string
	}{
		{name: "writes a stable version as it is", version: "1.5.0", entry: "    release-notes (1.5.0)"},
		{name: "writes a pre-release the way Bundler records it", version: "1.5.0-rc.1", entry: "    release-notes (1.5.0.pre.rc.1)"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := updater.UpdateGemfileLock(gemfileLock, "release-notes", tc.version)
			if err != nil {
				t.Fatalf("UpdateGemfileLock() error = %v", err)
			}
			want := replaceLine(gemfileLock, "    release-notes (1.4.0)", tc.entry)
			if got != want {
				t.Fatalf("UpdateGemfileLock() =\n%s\nwant\n%s", got, want)
			}
		})
	}
}

